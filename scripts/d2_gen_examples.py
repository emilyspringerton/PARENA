#!/usr/bin/env python3
"""Regenerates stdlib/d2/web/d2_examples.prn: the ships the EXAMPLE button lays on the grid.
   scripts/d2_gen_examples.py /path/to/DEADWEIGHT_2/apps/bot/loadouts.h > stdlib/d2/web/d2_examples.prn

Four are drawn here (each teaches one idea of ruleset 2) and four are the best ship of each weapon family from the bot pool (loadouts.h, the C search's output).
A drawn ship is six rows of six cells, two characters a cell: a letter for the part and a digit for its rotation (quarter turns clockwise); ".." empty, "--" covered
by a multi-cell part written once at its top-left cell. Letters are the same as DEADWEIGHT_2/tools/dw2_trace.c, which can play two drawn ships against each other
and price them (`dw2_trace A.txt A.txt --ops`):
  G generator  c conductor  s splitter  R railgun  B bulwark  T titanium beam  O aether ore  L pulse laser  C siege cannon  A amplifier  M mender  E aegis
  1 2 4 resistors  P capacitor  Y battery  X transistor  D delayer  Q quantum core  V cryo-vent  N xeno-biomass  t titanium shard  o ore chip"""
import re, sys

LET = "GcsRBTOLCAME124PYXDQVNto"

def parse(art):
    rows = [r for r in art.strip('\n').split('\n')]
    assert len(rows) == 6, art
    ops = []
    for r, line in enumerate(rows):
        line = line.replace(' ', '')
        assert len(line) == 12, (r, line)
        for c in range(6):
            a, b = line[2 * c], line[2 * c + 1]
            if a in '.-':
                continue
            ops.append((LET.index(a), r, c, int(b)))
    return ops

DRAWN = [
    ('Hot core', """
.. .. .. .. .. ..
.. .. .. .. .. ..
.. L3 V0 -- .. ..
Q0 -- R0 .. .. ..
-- -- .. .. .. ..
.. .. .. .. .. ..
"""),
    ('Repair cross', """
.. .. .. .. .. ..
.. .. .. .. .. ..
.. .. L3 .. .. ..
G0 c0 s0 B0 .. ..
.. B0 E1 B0 .. ..
.. .. B0 .. .. ..
"""),
]

# what each of the bot pool's hand-drawn strategies is, for the button's label (DEADWEIGHT_2/tools/dw2_loadout_search.c ARCH[])
STRATEGY = {0: 'Laser line x4', 1: 'Laser line x3', 2: 'Titanium wall, rails', 4: 'Aether wall, rails', 7: 'Cannon battery', 8: 'Cannons and a rail', 9: 'Plated cannons'}

def main():
    t = open(sys.argv[1]).read()
    rows = [l for l in t.splitlines() if l.strip().startswith('{ ') and ('strategy' in l or 'evolved' in l)]
    ex = [(n, parse(a)) for n, a in DRAWN]
    evolved = 0
    for l in rows:
        fam = re.search(r'/\* (\w[\w-]*),', l).group(1)
        ops = [tuple(map(int, o)) for o in re.findall(r'\{(\d+),(\d+),(\d+),(\d+)\}', l)]
        m = re.search(r'strategy (\d+)', l)
        if m:
            ex.append(('Bot: ' + STRATEGY.get(int(m.group(1)), 'strategy %s' % m.group(1)), ops))
        elif evolved < 3:
            evolved += 1
            ex.append(('Bot: evolved %s' % fam, ops))
    ex = ex[:12]
    base = 266240
    o = ';; stdlib/d2/web/d2_examples.prn -- GENERATED by scripts/d2_gen_examples.py from DEADWEIGHT_2/apps/bot/loadouts.h. Do not hand-edit.\n'
    o += ";; Ships the EXAMPLE button lays on the grid: two drawn ones that each teach an idea (a hot Quantum Core cooled by a Cryo-Vent; an Aegis Emitter mending the plates round it)\n"
    o += ";; and the bot pool's: the human strategies (a row of lasers, a Titanium wall with railguns behind it, an Aether wall, cannons ...) and a few evolved ships. Each has a counter.\n\n"
    o += '(defn example-count [] : I32 %d)\n' % len(ex)
    o += '(defn example-name [(k : I32)] : String (case k %s))\n' % ' '.join('%d "%s"' % (i, n) if i < len(ex) - 1 else '"%s"' % n for i, (n, _) in enumerate(ex))
    o += '(defn examples-init! [] : Unit\n  (do\n'
    for k, (n, ops) in enumerate(ex):
        a = base + k * 160
        o += '    ;; %s: %d parts\n    (store8! %d %d)\n' % (n, len(ops), a, len(ops))
        for j, op in enumerate(ops):
            for q in range(4):
                o += '    (store8! %d %d)\n' % (a + 8 + j * 4 + q, op[q])
    o = o.rstrip('\n') + '))\n'
    o += '\n(defn examples-base [] : I32 %d)\n(defn ex-n [(k : I32)] : I32 (load8 (+ (examples-base) (* k 160))))\n' % base
    o += '(defn ex-op [(k : I32) (j : I32) (q : I32)] : I32 (load8 (+ (examples-base) (+ (* k 160) (+ 8 (+ (* j 4) q))))))\n'
    sys.stdout.write(o)

main()
