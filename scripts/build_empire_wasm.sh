#!/usr/bin/env bash
# Builds the EMPIRE web module (stdlib/empire/web/*.prn) to a native wasm32 module -- no Emscripten, same toolchain as D2 web / BRAWLPIT web:
# parena build -> opt -> llc -> wasm-ld. The SAME module is what the browser plays and what IDUNA steps headlessly as the referee.
#
#   scripts/build_empire_wasm.sh <out.wasm>
#
# "No malloc": no allocator, no imports, fixed 4 MB of linear memory. After linking the script asserts the module imports NOTHING.
set -euo pipefail
cd "$(dirname "$0")/.."
OUT="${1:?usage: build_empire_wasm.sh <out.wasm>}"
TC="${LLVM_TOOLCHAIN_ROOT:-$HOME/.local/opt/llvm-toolchain}"
BIN="$TC/usr/lib/llvm-18/bin"
export LD_LIBRARY_PATH="$TC/usr/lib/x86_64-linux-gnu:$TC/usr/lib/llvm-18/lib:${LD_LIBRARY_PATH:-}"
PARENA="${PARENA_BIN:-./.parena-bootstrap}"
[ -x "$PARENA" ] || make .parena-bootstrap >/dev/null
W="$(mktemp -d)"; trap 'rm -rf "$W"' EXIT

# The sim version: a hash of the files that decide what a tick does (rules + sim; the AIs run only on the server, the screens only in the browser).
# A client and the server must agree on it or they would drift apart; the server refuses a page built from a different one.
VER=$(cat stdlib/empire/web/em_rules.prn stdlib/empire/web/em_sim.prn | sha256sum | cut -c1-7)
printf ';; generated by scripts/build_empire_wasm.sh -- do not edit\n(defn sim-version [] : I32 %d)\n' "$((16#$VER))" > "$W/em_ver.prn"

SRC=()
while IFS= read -r line; do
  case "$line" in
    "#"*|"") ;;
    GENERATED:em_ver) SRC+=("$W/em_ver.prn") ;;
    *) SRC+=("$line") ;;
  esac
done < stdlib/empire/web/MODULES
SRC+=(stdlib/gfd/term_font.prn)   # the 8x16 bitmap font (font-hex), shared with the GFD terminal

cat "${SRC[@]}" > "$W/em_all.prn"
"$PARENA" build "$W/em_all.prn" -o "$W/em.ll"
"$BIN/opt" -O2 -S "$W/em.ll" -o "$W/em.opt.ll"
"$BIN/llc" -O2 -mtriple=wasm32-unknown-unknown -filetype=obj "$W/em.opt.ll" -o "$W/em.o"
if "$BIN/llvm-nm" "$W/em.o" | grep -Eqw '(malloc|calloc|realloc|free|sbrk|brk|memalign|posix_memalign|aligned_alloc)'; then
  echo "FAIL: an allocator symbol is present in the object code" >&2; exit 1
fi
if "$BIN/llvm-objdump" -d "$W/em.o" | grep -Eq 'memory\.grow'; then
  echo "FAIL: the module contains a memory.grow instruction" >&2; exit 1
fi
# 4 MB linear memory, fixed (no growth, ever). The stack stays below 0x20000, below every fixed region.
"$BIN/wasm-ld" --no-entry --export-all --allow-undefined --export-memory \
  --initial-memory=4194304 --max-memory=4194304 -z stack-size=65536 -o "$OUT" "$W/em.o"

if command -v node >/dev/null 2>&1; then
  node --input-type=module -e "
import fs from 'node:fs';
const m = new WebAssembly.Module(fs.readFileSync(process.argv[1]));
const imp = WebAssembly.Module.imports(m);
if (imp.length) { console.error('FAIL: module has imports (a libcall leaked in): ' + JSON.stringify(imp)); process.exit(1); }
" "$OUT"
fi
echo "built $OUT ($(wc -c < "$OUT") bytes, 0 imports, fixed 4 MB memory, no allocator)"
