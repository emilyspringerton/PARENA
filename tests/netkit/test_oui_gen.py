"""stdlib/netkit/nk_oui_gen.prn (the maker-table generator) through scripts/build_netkit_oui.sh -- the real build path: PARENA wasm +
PARENA->TS host under node. A small hand-written registry in Wireshark's manuf layout exercises every rule kind and every error.
(On the real 3 MB registry the PARENA curate reproduced the first Python generator's 14,052 lines exactly; that file is not checked in.)"""
import os, sys, struct, subprocess, tempfile
sys.path.insert(0, os.path.dirname(__file__))
from nkharness import check, done

HERE = os.path.dirname(os.path.abspath(__file__))
TOOL = os.path.join(HERE, "../../scripts/build_netkit_oui.sh")
W = tempfile.mkdtemp()
def run(*args):
    r = subprocess.run([TOOL, *args], capture_output=True, text=True)
    return r.returncode, r.stdout + r.stderr
def put(name, text):
    p = os.path.join(W, name); open(p, "w", encoding="utf-8").write(text); return p

MANUF = put("manuf", "\n".join([
    "# This file was generated by TShark ...",
    "#",
    "00:00:00      58895",                                              # no tab: skipped
    "00:00:0C\tCisco\tCisco Systems, Inc",                               # Cisco
    "00:00:0D\tFibronic\tFibronics Ltd.",                                # no brand: dropped
    "00:18:0A\tCiscoMeraki\tCisco Meraki",                               # Meraki, not Cisco (Meraki is checked first)
    "00:1B:21\tIntel\t  Intel Corporate  ",                              # the registered name is trimmed
    "08:00:09\tHP\tHewlett Packard",                                     # HP: the exact rule
    "08:00:0A\tHPE\tHewlett Packard Enterprise",                         # not HP (exact), but Aruba / HPE
    "0C:8B:FD\tIntel\tIntel Corporate",
    "14:A7:8B\tZhejiang\tZhejiang Dahua Technology Co., Ltd.",           # a contains rule
    "1C:1B:0D\tGiga-Byt\tGIGA-BYTE",                                     # dropped
    "28:CD:C1\tRaspberryPiT",                                            # no third column: the short name is used -> no brand ("RaspberryPiT")
    "3A:35:41\tRaspberryPi \tRaspberry Pi (Trading) Ltd",
    "8C:1F:64:34:A0/36\tRaspberryPi \tRaspberry Pi (Trading) Ltd",       # a 36-bit block: skipped
    "B8:27:EB\tRaspberryPiF\tRaspberry Pi Foundation",
    "dc:a6:32\tRaspberryPiT\tRaspberry Pi Trading Ltd",                  # lower-case hex in, lower-case out
    "",
]))
code, out = run("--curate", MANUF, os.path.join(W, "out.tsv"))
check(code == 0, f"curate runs ({out.strip()})")
got = [l for l in open(os.path.join(W, "out.tsv"), encoding="utf-8").read().split("\n") if l and not l.startswith("#")]
want = ["00:00:0c\tCisco", "00:18:0a\tMeraki", "00:1b:21\tIntel", "08:00:09\tHP", "08:00:0a\tAruba / HPE", "0c:8b:fd\tIntel",
        "14:a7:8b\tDahua (camera)", "3a:35:41\tRaspberry Pi", "b8:27:eb\tRaspberry Pi", "dc:a6:32\tRaspberry Pi"]
check(got == want, "curate keeps exactly the branded 24-bit blocks, first rule wins, names trimmed, hex lower-cased" + ("" if got == want else f": {got}"))
check(open(os.path.join(W, "out.tsv")).read().startswith("# Netkit manufacturer table -- generated by PARENA"), "the TSV says PARENA made it")

code, out = run("--curate", put("unsorted", "B8:27:EB\tx\tRaspberry Pi Foundation\n28:CD:C1\tx\tRaspberry Pi Trading Ltd\n"), os.path.join(W, "x"))
check(code != 0 and ":2: prefixes are not in ascending order" in out, f"curate refuses a registry out of order, naming the line ({out.strip()})")
code, out = run("--curate", put("badhex", "ZZ:27:EB\tx\tApple, Inc.\n"), os.path.join(W, "x"))
check(code != 0 and ":1: malformed line" in out, "curate refuses a malformed prefix")

# ---- pack -------------------------------------------------------------------------------------------------------------------------------
def pack(text):
    o = os.path.join(W, "o.bin")
    if os.path.exists(o): os.remove(o)
    code, out = run(o, put("p.tsv", text))
    return code, out, (open(o, "rb").read() if code == 0 else b"")
code, out, b = pack("# c\n\n00:1b:21\tIntel\n08:00:09\tHP\nb8:27:eb\tRaspberry Pi\ndc:a6:32\tRaspberry Pi\n")
n, m, off = struct.unpack("<III", b[4:16]) if b else (0, 0, 0)
check(code == 0 and b[:4] == b"NKOU" and (n, m, off) == (4, 4, 32), f"pack writes the header: 4 prefixes, 3 makers + the empty one ({out.strip()})")
names = [b[off + 24 * i: off + 24 * i + 24].rstrip(b"\0").decode() for i in range(m)] if b else []
check(names == ["", "HP", "Intel", "Raspberry Pi"], f"maker names are sorted bytewise after the empty maker 0 ({names})")
ents = [struct.unpack("<I", b[16 + 4 * i:20 + 4 * i])[0] for i in range(n)] if b else []
check([(e & 0xFFFFFF, e >> 24) for e in ents] == [(0x001B21, 2), (0x080009, 1), (0xB827EB, 3), (0xDCA632, 3)], "entries: prefix | maker << 24, in prefix order")
check(len(b) == 16 + 4 * 4 + 24 * 4, "nothing after the name table")
for desc, text, msg in [
    ("prefixes out of order", "b8:27:eb\tA\n00:1b:21\tB\n", ":2: prefixes are not in ascending order"),
    ("a duplicate prefix", "b8:27:eb\tA\nb8:27:eb\tB\n", ":2: prefixes are not in ascending order"),
    ("a maker name over 23 bytes", "b8:27:eb\t" + "x" * 24 + "\n", ":1: maker name longer than 23 bytes"),
    ("a line with no tab", "b8:27:eb Raspberry Pi\n", ":1: malformed line"),
    ("more than 255 makers", None, None),
]:
    if msg is None:   # 256 distinct names: build it with a valid aa:bb:cc layout
        text = "".join("00:%02x:%02x\tM%d\n" % (i >> 8, i & 255, i) for i in range(256)); msg = ":256: more than 255 makers"
    code, out, _ = pack(text)
    check(code != 0 and msg in out, f"pack refuses {desc}, naming the line ({out.strip().splitlines()[-1] if out.strip() else ''})")
code, out, _ = pack("".join("%02x:%02x:%02x\tA\n" % (i >> 16, (i >> 8) & 255, i & 255) for i in range(16380)))
check(code != 0 and "64 KB" in out, "pack refuses a table that would not fit the scanner's 64 KB region")
check(open(os.path.join(HERE, "../../stdlib/netkit/data/oui_brands.tsv")).read().startswith("# Netkit manufacturer table -- generated by PARENA"), "the checked-in TSV was made by PARENA")
code, out = run(os.path.join(W, "real.bin"))
check(code == 0 and open(os.path.join(W, "real.bin"), "rb").read()[:4] == b"NKOU", "the checked-in TSV packs (the page build's own call)")
done()
