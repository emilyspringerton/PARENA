// tests/br_golden.mjs -- prints the golden match-state hashes IDUNA's Go test (internal/bedrockracers/golden_test.go) compares wazero against.
// The module is stepped here in V8 (the browsers' engine) through a scripted match; the Go test replays the very same command stream in wazero
// (goldenCmd in engine_test.go must stay equal to goldenCmd below). Equal hashes = the referee reaches the browsers' match, bit for bit.
//   node tests/br_golden.mjs <bedrockracers.wasm>      -> Go source for goldenHashes
import fs from 'node:fs';
const wasm = process.argv[2];
if (!wasm) { console.error('usage: br_golden.mjs <wasm>'); process.exit(2); }
const { instance } = await WebAssembly.instantiate(fs.readFileSync(wasm), {});
const x = instance.exports;
x.br_init_sim();
x.br_net_begin(777, 3, (1 << 1) | (1 << 6), 1);
const goldenCmd = (slot, t) => {
  if (slot === 1) {
    return [t % 40 < 25 ? 127 : 0, t % 90 < 30 ? 80 : 0xB0, 0, 0, 0, 0, t % 7 === 0 ? 5 : 1, 0];
  }
  return [t % 60 >= 45 ? 0x81 : 127, t % 50 < 20 ? 100 : 0, 0, 0, 0, (t % 3) * 100, Math.floor((t % 30) / 10) * 2, 0];
};
const marks = [300, 1000, 2500, 5000, 8000];
const out = {};
let t = 0;
for (const upTo of marks) {
  for (; t < upTo; t++) {
    new Uint8Array(x.memory.buffer, x.br_net_pend_addr() + 1 * 8, 8).set(goldenCmd(1, t));
    new Uint8Array(x.memory.buffer, x.br_net_pend_addr() + 6 * 8, 8).set(goldenCmd(6, t));
    x.br_net_tick();
  }
  out[upTo] = x.br_net_hash() >>> 0;
}
console.log('package bedrockracers\n\n// generated by PARENA/tests/br_golden.mjs from bedrockracers.wasm (sim version ' + x.br_version() + '): match state hashes in V8 after n ticks\nvar goldenHashes = map[int]uint32{');
for (const k of marks) console.log(`\t${k}: ${out[k]},`);
console.log('}');
