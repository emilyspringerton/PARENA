#!/usr/bin/env python3
"""Generates stdlib/brawlpit/bp_fields.prn -- the PlayerState / Turnip / EdgeKO field accessors for
the BRAWLPIT web engine (BRAWLPIT/packages/common/protocol.h ported to PARENA).

PARENA's wasm backend has no structs and no globals (CLAUDE.md: "no malloc"), so every record lives
at a fixed address in linear memory as an array of 32-bit words. This file is the one place the
word layout is written down; the generated .prn is checked in (same convention as
tools/gfd_font_gen.py -> stdlib/gfd/term_font.prn). Run from the PARENA repo root:

    python3 tools/bp_fields_gen.py > stdlib/brawlpit/bp_fields.prn

Each field yields:  (k-NAME)  word index   (p-NAME p)  getter   (set-p-NAME! p v)  setter
where p is the player slot 0..7. Turnips use t-NAME / set-t-NAME! over (t) slot 0..15, edge-KO
effects use e-NAME / set-e-NAME! over slot 0..15. 'i' = I32 word, 'f' = F32 word.
"""

PLAYER = [
    ("id", "i"), ("character-id", "i"), ("active", "i"), ("is-bot", "i"),
    ("x", "f"), ("y", "f"), ("vx", "f"), ("vy", "f"),
    ("on-ground", "i"), ("facing", "i"),
    ("in-x", "f"), ("in-y", "f"),
    ("btn-jump", "i"), ("btn-jump-prev", "i"), ("btn-attack", "i"), ("btn-attack-prev", "i"),
    ("btn-shield", "i"), ("btn-shield-prev", "i"), ("btn-special", "i"), ("btn-special-prev", "i"),
    ("state", "i"), ("damage-percent", "f"), ("stocks", "i"), ("shield-health", "f"),
    ("shield-regen-timer", "i"), ("shield-stun-frames", "i"), ("shield-drop-timer", "i"),
    ("shield-windup-frames", "i"), ("shield-overpowered-frames", "i"),
    ("jumps-remaining", "i"), ("ground-platform-type", "i"), ("drop-through-timer", "i"),
    ("wavedash-frames", "i"), ("dash-cooldown", "i"), ("special-b-cooldown", "i"),
    ("umbrella-open", "i"), ("upb-frame", "i"), ("upb-landing-lag", "i"),
    ("parasol-rehit-timer", "i"), ("rosie-dash-frame", "i"),
    ("hitlag-frames", "i"), ("hit-flash-timer", "i"), ("hit-flash-multihit", "i"),
    ("hitstun-frames", "i"), ("attack-cooldown", "i"), ("attack-timer", "i"), ("parry-timer", "i"),
    ("smash-charge-timer", "i"), ("smash-active-timer", "i"), ("smash-charge-level", "f"),
    ("launch-delay-frames", "i"), ("pending-kb-x", "f"), ("pending-kb-y", "f"),
    ("smash-release-timer", "i"), ("smash-flash-timer", "i"),
    ("invuln-frames", "i"), ("respawn-timer", "i"), ("kills", "i"), ("deaths", "i"),
    # --- web-client-only words (not in protocol.h) ---
    ("hat", "i"),          # hat slot 0..7 in the hat atlas, -1 none
    ("pad", "i"),          # controller index driving this slot, -1 none
    ("team-color", "i"),   # 0x00BBGGRR tint that tells identical characters apart
    ("bot-think", "i"),    # smash-charge frames left (web CPU only)
    ("last-hit-by", "i"),  # slot that last damaged this player, -1 none (kill credit)
    ("prev-x", "f"), ("prev-y", "f"),   # position before the last tick (KO effect origin)
    ("prev-stocks", "i"), ("prev-resp", "i"), ("prev-hitlag", "i"),
    ("label", "i"),        # 0 none, 1 P1, 2 P2, 3 CPU -- name tag above the head
    ("bot-shield", "i"),   # shield frames left to hold (web CPU only)
]

TURNIP = [
    ("active", "i"), ("x", "f"), ("y", "f"), ("vx", "f"), ("vy", "f"),
    ("owner-id", "i"), ("ttl-frames", "i"), ("style", "i"),
]

EDGEKO = [("active", "i"), ("x", "f"), ("y", "f"), ("intensity", "f"), ("timer", "i")]


def emit(prefix, base_fn, fields, out):
    for idx, (name, ty) in enumerate(fields):
        t = "F32" if ty == "f" else "I32"
        get = "loadf32" if ty == "f" else "load32"
        put = "storef32!" if ty == "f" else "store32!"
        addr = "(+ (%s s) %d)" % (base_fn, idx * 4)
        out.append("(defn k-%s-%s [] : I32 %d)" % (prefix, name, idx) if prefix != "p" else "(defn k-%s [] : I32 %d)" % (name, idx))
        out.append("(defn %s-%s [(s : I32)] : %s (%s %s))" % (prefix, name, t, get, addr))
        out.append("(defn set-%s-%s! [(s : I32) (v : %s)] : Unit (%s %s v))" % (prefix, name, t, put, addr))


def main():
    out = [";; GENERATED by tools/bp_fields_gen.py -- do not edit. Field accessors for the BRAWLPIT web engine's",
           ";; fixed-address records (players, turnips, edge-KO effects). See that script for the layout.", ""]
    emit("p", "pl-base", PLAYER, out)
    out.append("")
    emit("t", "tn-base", TURNIP, out)
    out.append("")
    emit("e", "ek-base", EDGEKO, out)
    out.append("")
    out.append("(defn player-words [] : I32 %d)" % len(PLAYER))
    print("\n".join(out))


if __name__ == "__main__":
    main()
