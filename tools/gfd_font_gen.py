#!/usr/bin/env python3
"""Rasterize DejaVu Sans Mono into the 8x16 bitmap table stdlib/gfd/term.prn embeds.

BUILD-TIME STOPGAP (CLAUDE.md "Core deps are PARENA-first"): font rasterization uses Pillow here;
the OUTPUT (stdlib/gfd/term_font.prn) is committed data and the terminal itself never needs this
script. PARENA replacement item: a PARENA-native glyph rasterizer (tracked in EMILY/BACKLOG.md).

DejaVu fonts are under the Bitstream Vera / DejaVu license, which permits derivative bitmaps.

Glyph index map (must match term.prn's glyph-index):
  0..94    ASCII 32..126
  95..222  U+2500..U+257F box drawing
  223..254 U+2580..U+259F block elements
Each glyph is 16 bytes (one per row, MSB = leftmost pixel), emitted as 32 hex chars.
"""
import sys
from PIL import Image, ImageDraw, ImageFont

FONT = "/usr/share/fonts/truetype/dejavu/DejaVuSansMono.ttf"
W, H = 8, 16

def codepoints():
    yield from range(32, 127)
    yield from range(0x2500, 0x2580)
    yield from range(0x2580, 0x25A0)

def main(out):
    font = ImageFont.truetype(FONT, 13)
    asc, desc = font.getmetrics()
    hexes = []
    for cp in codepoints():
        im = Image.new("L", (W, H), 0)
        d = ImageDraw.Draw(im)
        ch = chr(cp)
        if 0x2500 <= cp < 0x25A0:
            # Box/block glyphs must tile edge to edge, so draw them full-cell at native size
            # rather than through the text baseline.
            d.text((0, 0), ch, font=ImageFont.truetype(FONT, 16), fill=255)
        else:
            d.text((0, 1 + (H - 2 - (asc + desc)) // 2), ch, font=font, fill=255)
        rows = []
        for y in range(H):
            b = 0
            for x in range(W):
                if im.getpixel((x, y)) >= 110:
                    b |= 0x80 >> x
            rows.append(b)
        hexes.append("".join("%02x" % r for r in rows))
    blob = "".join(hexes)
    assert len(blob) == 255 * 32
    with open(out, "w") as f:
        f.write(";; GENERATED by tools/gfd_font_gen.py -- do not edit. 255 glyphs x 16 rows, hex.\n")
        f.write("(defn font-hex [] : String\n  \"%s\")\n" % blob)
    # ASCII preview so a human can eyeball the result
    for cp in (ord('A'), ord('g'), ord('@'), 0x2500, 0x2588):
        i = list(codepoints()).index(cp)
        print(chr(cp), hex(cp))
        for y in range(H):
            b = int(hexes[i][y*2:y*2+2], 16)
            print("".join("#" if b & (0x80 >> x) else "." for x in range(W)))

if __name__ == "__main__":
    main(sys.argv[1])
