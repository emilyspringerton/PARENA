#!/usr/bin/env python3
"""Generates stdlib/shankpit460/sp_map_data.prn from shankpit-460's own map file (maps/v0_shankpit.map,
the launch deathmatch map, in the external map format of packages/common/map_loader.h).

    python3 tools/sp_map_gen.py <path/to/maps/v0_shankpit.map> > stdlib/shankpit460/sp_map_data.prn

The map file is parsed exactly like map_load_file does (box / spawn / poi lines, '#' comments); the
result is a pure PARENA init function that writes the boxes and spawns into the engine's fixed tables.
"""
import sys


def main():
    path = sys.argv[1]
    boxes, spawns, pois = [], [], []
    for raw in open(path):
        line = raw.split('#', 1)[0].strip()
        if not line:
            continue
        parts = line.split()
        kw = parts[0]
        if kw == 'box':
            b = [float(v) for v in parts[1:7]]
            assert len(b) == 6 and b[3] > 0 and b[4] > 0 and b[5] > 0, line
            boxes.append(b)
        elif kw == 'spawn':
            spawns.append([float(v) for v in parts[1:4]])
        elif kw == 'poi':
            pois.append((parts[1], [float(v) for v in parts[2:5]]))
        else:
            raise SystemExit("unknown keyword %r" % kw)
    assert len(boxes) >= 2 and len(boxes) <= 64 and len(spawns) <= 16
    f = lambda v: repr(float(v))
    out = [";; GENERATED by tools/sp_map_gen.py from shankpit-460/maps/v0_shankpit.map -- do not edit.",
           ";; %d boxes (index 0 is the floor slab, skipped by collision exactly as in map_loader.h), %d spawns."
           % (len(boxes), len(spawns)), ""]
    out.append("(defn map-box-count-const [] : I32 %d)" % len(boxes))
    out.append("(defn map-spawn-count-const [] : I32 %d)" % len(spawns))
    out.append("(defn map-init-data! [] : Unit")
    out.append("  (do")
    for i, b in enumerate(boxes):
        out.append("    (map-set-box! %d %s)" % (i, " ".join(f(v) for v in b)))
    for i, s in enumerate(spawns):
        out.append("    (map-set-spawn! %d %s)" % (i, " ".join(f(v) for v in s)))
    for name, p in pois:
        if name == 'rocket_launcher':
            out.append("    (map-set-crown! %s)" % " ".join(f(v) for v in p))
    out.append("    (map-set-counts! %d %d)))" % (len(boxes), len(spawns)))
    print("\n".join(out))


main()
