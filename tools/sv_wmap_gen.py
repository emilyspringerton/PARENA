#!/usr/bin/env python3
"""Compile stdlib/shankpit_survival/survival_city.wmap (WORLDMAP v1) to stdlib/shankpit_survival/sv_crystal_data.prn.

    tools/sv_wmap_gen.py            # write the .prn
    tools/sv_wmap_gen.py --check    # exit 1 if the committed .prn is stale (the survival test runs this)

Only the entries SURVIVAL uses are read (`worldmap`, `zone`, `bound`, `crystal`); anything else is rejected rather than
ignored, so a file that grows a `box` line fails loudly here instead of silently shipping without it.
"""
import os, sys

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, "..", "stdlib", "shankpit_survival", "survival_city.wmap")
OUT = os.path.join(HERE, "..", "stdlib", "shankpit_survival", "sv_crystal_data.prn")
MAX_CRYSTALS = 8
MAX_PROMPT = 40

def fail(msg):
    sys.exit("sv_wmap_gen: " + msg)

def parse(text):
    zone = bound = None
    crystals = []
    version = None
    for n, raw in enumerate(text.splitlines(), 1):
        line = raw.split("#", 1)[0].strip()
        if not line:
            continue
        f = line.split()
        k = f[0]
        if k == "worldmap":
            version = f[1]
            if version != "1": fail(f"line {n}: worldmap version {version} (this reader is v1)")
        elif k == "zone":
            if len(f) < 4: fail(f"line {n}: zone <id> <kind> <name>")
            zone = int(f[1])
            if f[2] not in ("town", "field", "dungeon", "arena"): fail(f"line {n}: zone kind {f[2]}")
        elif k == "bound":
            bound = float(f[1])
        elif k == "crystal":
            if len(f) < 13: fail(f"line {n}: crystal needs 11 numbers/ids and a prompt")
            cid = f[1]
            x, z, r = float(f[2]), float(f[3]), float(f[4])
            dz_, dx, dzz, yaw = int(f[5]), float(f[6]), float(f[7]), float(f[8])
            cost, total, commit = int(f[9]), int(f[10]), int(f[11])
            prompt = " ".join(f[12:])
            crystals.append(dict(id=cid, x=x, z=z, r=r, dest_zone=dz_, dx=dx, dz=dzz, yaw=yaw,
                                 cost=cost, total=total, commit=commit, prompt=prompt, line=n))
        else:
            fail(f"line {n}: `{k}` is not read by SURVIVAL (it has no geometry here: sv_city.prn builds it)")
    if version is None: fail("missing `worldmap 1`")
    if zone is None or bound is None: fail("missing zone / bound")
    if not crystals: fail("no crystals")
    if len(crystals) > MAX_CRYSTALS: fail(f"{len(crystals)} crystals (max {MAX_CRYSTALS})")
    seen = set()
    for c in crystals:
        w = f"line {c['line']} ({c['id']})"
        if c["id"] in seen: fail(f"{w}: duplicate id")
        seen.add(c["id"])
        if c["dest_zone"] != zone: fail(f"{w}: dest_zone {c['dest_zone']} != zone {zone} (SURVIVAL is one level)")
        if not (0 < c["r"] <= 40): fail(f"{w}: radius")
        if c["cost"] < 0: fail(f"{w}: cost")
        if not (0 < c["commit"] <= c["total"]): fail(f"{w}: need 0 < commit_ms <= total_ms")
        if len(c["prompt"]) > MAX_PROMPT or not all(32 <= ord(ch) < 127 and ch != '"' and ch != "\\" for ch in c["prompt"]):
            fail(f"{w}: prompt must be <= {MAX_PROMPT} printable ASCII chars without quotes")
        for lab, (a, b) in (("position", (c["x"], c["z"])), ("destination", (c["dx"], c["dz"]))):
            if abs(a) > bound or abs(b) > bound: fail(f"{w}: {lab} outside bound {bound}")
    return zone, bound, crystals

def f32(v):
    s = repr(float(v))
    return s if ("." in s or "e" in s) else s + ".0"

def emit(zone, bound, cs):
    o = []
    o.append(";; GENERATED by tools/sv_wmap_gen.py from stdlib/shankpit_survival/survival_city.wmap -- do not edit.")
    o.append(";; SURVIVAL's telecrystals (WORLDMAP v1 `crystal` rows). The hero lands at the absolute point (dx, dz), facing yaw degrees.")
    o.append("")
    o.append(f"(defn svx-zone [] : I32 {zone})")
    o.append(f"(defn svx-n [] : I32 {len(cs)})")
    def tbl(name, ty, vals):
        arms = " ".join(f"{i} {v}" for i, v in enumerate(vals[:-1]))
        last = vals[-1]
        # a `case` with the last value as the default arm
        o.append(f"(defn {name} [(i : I32)] : {ty} (case i {arms} {last}))" if len(vals) > 1
                 else f"(defn {name} [(i : I32)] : {ty} {last})")
    tbl("svx-x", "F32", [f32(c["x"]) for c in cs])
    tbl("svx-z", "F32", [f32(c["z"]) for c in cs])
    tbl("svx-r", "F32", [f32(c["r"]) for c in cs])
    tbl("svx-dx", "F32", [f32(c["dx"]) for c in cs])
    tbl("svx-dz", "F32", [f32(c["dz"]) for c in cs])
    tbl("svx-yaw-deg", "F32", [f32(c["yaw"]) for c in cs])
    tbl("svx-cost", "I32", [str(c["cost"]) for c in cs])
    tbl("svx-total-ms", "I32", [str(c["total"]) for c in cs])
    tbl("svx-commit-ms", "I32", [str(c["commit"]) for c in cs])
    tbl("svx-prompt", "String", ['"%s"' % c["prompt"] for c in cs])
    return "\n".join(o) + "\n"

def main():
    zone, bound, cs = parse(open(SRC).read())
    out = emit(zone, bound, cs)
    if "--check" in sys.argv:
        cur = open(OUT).read() if os.path.exists(OUT) else ""
        if cur != out:
            sys.exit("sv_wmap_gen: sv_crystal_data.prn is stale -- run tools/sv_wmap_gen.py")
        print("sv_crystal_data.prn is current (%d crystals)" % len(cs))
        return
    open(OUT, "w").write(out)
    print("wrote %s (%d crystals)" % (os.path.relpath(OUT), len(cs)))

main()
