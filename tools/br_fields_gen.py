#!/usr/bin/env python3
"""Generates stdlib/bedrockracers/web/br_fields.prn -- field accessors for the BEDROCK RACERS web engine's
fixed-address records (cars, the ball, particles). Same convention as tools/sp_fields_gen.py: PARENA's wasm backend has no
structs and no globals, so every record is an array of 32-bit words at a fixed address and this is the one place the
word layout is written down. Run from the PARENA repo root:

    python3 tools/br_fields_gen.py > stdlib/bedrockracers/web/br_fields.prn

Each CAR field yields  (k-NAME) word index,  (c-NAME s) getter,  (set-c-NAME! s v) setter  (s = car slot 0..11);
BALL fields b-NAME / set-b-NAME!; PARTICLE fields f-NAME / set-f-NAME! over a particle index.
'i' = I32 word, 'f' = F32 word.
"""

CAR = [
    ("id", "i"), ("active", "i"), ("is-bot", "i"), ("team", "i"), ("seat", "i"),
    # pose: position, velocity, the orientation basis (right, up, forward), angular rate in car axes (pitch, yaw, roll)
    ("x", "f"), ("y", "f"), ("z", "f"), ("vx", "f"), ("vy", "f"), ("vz", "f"),
    ("rx", "f"), ("ry", "f"), ("rz", "f"), ("ux", "f"), ("uy", "f"), ("uz", "f"), ("fx", "f"), ("fy", "f"), ("fz", "f"),
    ("wp", "f"), ("wy", "f"), ("wr", "f"),
    # the command for this tick (written by the human's input, a bot's brain, or the replay): all -1..1 except the buttons
    ("in-thr", "f"), ("in-steer", "f"), ("in-pitch", "f"), ("in-roll", "f"), ("in-strafe", "f"),
    ("in-lift", "f"), ("in-boost", "i"), ("in-fans-off", "i"),
    # state
    ("attached", "i"), ("sd", "f"), ("nx", "f"), ("ny", "f"), ("nz", "f"),
    ("air", "f"), ("air-wait", "i"), ("syn-bonus", "f"),
    ("lift-fx", "f"), ("boost-fx", "f"), ("strafe-fx", "f"), ("slip", "f"), ("surface", "i"),
    ("flip-t", "i"), ("stuck", "i"), ("respawn", "i"),
    # stats
    ("goals", "i"), ("assists", "i"), ("saves", "i"), ("touches", "i"), ("shots", "i"), ("own-goals", "i"),
    ("air-used", "f"), ("top-speed", "f"), ("ticks-up", "i"), ("ticks-inv", "i"),
    # render interpolation: pose at the start of the last tick
    ("px", "f"), ("py", "f"), ("pz", "f"),
    ("prx", "f"), ("pry", "f"), ("prz", "f"), ("pux", "f"), ("puy", "f"), ("puz", "f"), ("pfx", "f"), ("pfy", "f"), ("pfz", "f"),
    ("color", "i"), ("net-slot", "i"),
    # the brain
    ("g-aggr", "f"), ("g-patience", "f"), ("g-risk", "f"), ("g-thrift", "f"), ("g-lead", "f"), ("g-react", "f"),
    ("g-noise", "f"), ("g-refuel", "f"), ("g-spread", "f"), ("g-guard", "f"), ("g-launch", "f"), ("g-turn", "f"),
    ("g-lift", "f"), ("g-style", "f"),
    ("role", "i"), ("tactic", "i"), ("tgt-x", "f"), ("tgt-y", "f"), ("tgt-z", "f"), ("aim-x", "f"), ("aim-y", "f"), ("aim-z", "f"),
    ("think", "i"), ("tact-t", "i"), ("level", "i"), ("genome", "i"), ("persona", "i"),
    ("want-boost", "i"), ("react-t", "i"), ("last-x", "f"), ("last-z", "f"), ("sk", "f"),
]

BALL = [
    ("x", "f"), ("y", "f"), ("z", "f"), ("vx", "f"), ("vy", "f"), ("vz", "f"),
    ("px", "f"), ("py", "f"), ("pz", "f"),
    ("touch", "i"), ("touch2", "i"), ("touch-team", "i"), ("touch-t", "i"), ("sx", "f"), ("sy", "f"), ("sz", "f"),
    ("hit-t", "i"), ("trail", "i"),
]

PART = [
    ("ttl", "i"), ("life", "i"), ("kind", "i"), ("color", "i"),
    ("x", "f"), ("y", "f"), ("z", "f"), ("vx", "f"), ("vy", "f"), ("vz", "f"), ("size", "f"),
]


def emit(prefix, setter, base, rows, tag, argn):
    out = []
    for i, (name, t) in enumerate(rows):
        n = f"{prefix}-{name}"
        out.append(f"(defn k{tag}-{name} [] : I32 {i})")
        if t == "i":
            out.append(f"(defn {n} [({argn} : I32)] : I32 (load32 (+ ({base} {argn}) {i*4})))")
            out.append(f"(defn set-{n}! [({argn} : I32) (v : I32)] : Unit (store32! (+ ({base} {argn}) {i*4}) v))")
        else:
            out.append(f"(defn {n} [({argn} : I32)] : F32 (loadf32 (+ ({base} {argn}) {i*4})))")
            out.append(f"(defn set-{n}! [({argn} : I32) (v : F32)] : Unit (storef32! (+ ({base} {argn}) {i*4}) v))")
    return out


print(";; GENERATED by tools/br_fields_gen.py -- do not edit. Field accessors for the BEDROCK RACERS web engine's")
print(";; fixed-address records (cars, ball, particles). See that script for the layout.\n")
for line in emit("c", "set-c", "car-base", CAR, "", "s"):
    print(line)
print(f";; car record: {len(CAR)} words (of 128)")
print("(defn car-words [] : I32 %d)\n" % len(CAR))
# ball: no index argument; the record is a singleton, accessors take a dummy
for i, (name, t) in enumerate(BALL):
    print(f"(defn kb-{name} [] : I32 {i})")
    if t == "i":
        print(f"(defn b-{name} [] : I32 (load32 (+ (ball-base) {i*4})))")
        print(f"(defn set-b-{name}! [(v : I32)] : Unit (store32! (+ (ball-base) {i*4}) v))")
    else:
        print(f"(defn b-{name} [] : F32 (loadf32 (+ (ball-base) {i*4})))")
        print(f"(defn set-b-{name}! [(v : F32)] : Unit (storef32! (+ (ball-base) {i*4}) v))")
print()
for line in emit("f", "set-f", "pa-base", PART, "f", "q"):
    print(line)
