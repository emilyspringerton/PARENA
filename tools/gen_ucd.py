#!/usr/bin/env python3
"""Generate stdlib/unicode/ucd.prn from Python's unicodedata (pinned version printed in the header).

Emits balanced binary-decision trees of integer comparisons -- no data tables, no inline-c, no
string-literal size limits (the lexer buffer is 4096 bytes). Run: python3 tools/gen_ucd.py > stdlib/unicode/ucd.prn
"""
import sys, unicodedata as ud

MAXCP = 0x110000
# property bits (packed into one I32)
ALPHA, UPPER, LOWER, DIGIT, SPACE, COMB, WIDE, PUNCT, CTRL = 1, 2, 4, 8, 16, 32, 64, 128, 256

def props(cp):
    c = chr(cp)
    cat = ud.category(c)
    v = 0
    if c.isalpha(): v |= ALPHA
    if c.isupper() or cat == 'Lt': v |= UPPER
    if c.islower(): v |= LOWER
    if cat == 'Nd': v |= DIGIT
    if cat in ('Zs', 'Zl', 'Zp') or cp in (9, 10, 11, 12, 13, 0x85): v |= SPACE
    if cat in ('Mn', 'Me'): v |= COMB
    if ud.east_asian_width(c) in ('W', 'F'): v |= WIDE
    if cat[0] == 'P': v |= PUNCT
    if cat == 'Cc': v |= CTRL
    return v

def ranges(f):
    out, start, cur = [], 0, f(0)
    for cp in range(1, MAXCP):
        v = f(cp)
        if v != cur:
            out.append((start, cur)); start, cur = cp, v
    out.append((start, cur))
    return out  # list of (start, value); value holds until next start

def tree(rs, lo, hi, ind):
    # rs[lo:hi] -> expression over `cp`
    if hi - lo == 1:
        return str(rs[lo][1])
    mid = (lo + hi) // 2
    return "(if (< cp %d)\n%s\n%s)" % (rs[mid][0], tree(rs, lo, mid, 0), tree(rs, mid, hi, 0))

def emit(name, doc, rs):
    # values for cp < 0 or >= MAXCP are 0
    print(";; %s -- %d ranges." % (doc, len(rs)))
    print("(defn %s [(cp : I32)]\n  : I32\n  (if (< cp 0) 0\n    (if (>= cp %d) 0\n      %s)))\n" %
          (name, MAXCP, tree(rs, 0, len(rs), 6)))

def lower_delta(cp):
    c = chr(cp); l = c.lower()
    return ord(l) - cp if len(l) == 1 and cp not in range(0xD800, 0xE000) else 0
def upper_delta(cp):
    c = chr(cp); u = c.upper()
    return ord(u) - cp if len(u) == 1 and cp not in range(0xD800, 0xE000) else 0

print(";; stdlib/unicode/ucd.prn -- GENERATED by tools/gen_ucd.py from Unicode %s. Do not hand-edit." % ud.unidata_version)
print(";; Property bits: ALPHA=1 UPPER=2 LOWER=4 DIGIT=8 SPACE=16 COMBINING=32 WIDE=64 PUNCT=128 CONTROL=256.")
print(";; Case mapping is the SIMPLE (1:1) mapping only -- no SpecialCasing (e.g. German sharp-s upper is left as-is).")
print(";; Every function is a balanced decision tree of integer comparisons: no data tables, no heap.")
print("(module ucd)")
print("(export ucd-props ucd-lower-delta ucd-upper-delta)\n")
emit("ucd-props", "packed property bits for a codepoint (0 for anything unassigned/out of range)", ranges(props))
emit("ucd-lower-delta", "add to a codepoint to lowercase it (0 = unchanged)", ranges(lower_delta))
emit("ucd-upper-delta", "add to a codepoint to uppercase it (0 = unchanged)", ranges(upper_delta))
